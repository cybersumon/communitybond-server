
import { ObjectId } from "mongodb";

import { getDatabase } from "../config/database.js";

import type {
  EventDocument,
  EventResponse,
} from "../types/event.types.js";

import type {
  CreateEventInput,
} from "../validators/create-event.validation.js";

/**
 * Event Service
 *
 * PURPOSE:
 * Keep MongoDB queries separate from API routes.
 *
 * WHY:
 * Routes handle HTTP.
 * Services handle database operations.
 */

/**
 * Access the events collection.
 */
function getEventsCollection() {
  return getDatabase().collection<EventDocument>("events");
}

/**
 * Convert MongoDB document into frontend-friendly data.
 */
function toEventResponse(
  event: EventDocument
): EventResponse {
  if (!event._id) {
    throw new Error("Event document is missing _id");
  }

  return {
    id: event._id.toHexString(),
    title: event.title,
    description: event.description,
    eventType: event.eventType,
    thumbnailUrl: event.thumbnailUrl,
    location: event.location,
    eventDate: event.eventDate.toISOString(),
    createdAt: event.createdAt.toISOString(),
    organizer: event.organizer,
  };
}

/**
 * GET ALL UPCOMING EVENTS
 *
 * Only events scheduled for now or the future.
 * Sort by nearest event date first.
 */
export async function getUpcomingEvents(): Promise<
  EventResponse[]
> {
  const now = new Date();

  const events = await getEventsCollection()
    .find({
      eventDate: { $gte: now },
    })
    .sort({
      eventDate: 1,
      _id: 1,
    })
    .toArray();

  return events.map(toEventResponse);
}

/**
 * GET LATEST SIX UPCOMING EVENTS
 *
 * Sort by creation date (newest first),
 * then limit MongoDB query to 6 records.
 */
export async function getRecentEvents(): Promise<
  EventResponse[]
> {
  const now = new Date();

  const events = await getEventsCollection()
    .find({
      eventDate: { $gte: now },
    })
    .sort({
      createdAt: -1,
      _id: -1,
    })
    .limit(6)
    .toArray();

  return events.map(toEventResponse);
}

/**
 * GET A SINGLE EVENT
 *
 * Accept a MongoDB ObjectId as a string.
 *
 * Returns null when the ID is invalid
 * or the event does not exist.
 */
export async function getEventById(
  id: string
): Promise<EventResponse | null> {
  if (!/^[a-fA-F0-9]{24}$/.test(id)) {
    return null;
  }

  const event = await getEventsCollection().findOne({
    _id: new ObjectId(id),
  });

  return event ? toEventResponse(event) : null;
}

/**
 * CREATE COMMUNITY EVENT
 *
 * PURPOSE:
 * Insert a new event into MongoDB.
 *
 * SECURITY:
 * - Organizer identity comes from a verified JWT.
 * - Organizer name comes from the database.
 * - createdAt is generated by the server.
 * - The user cannot choose another organizer.
 */
export async function createEvent(
  input: CreateEventInput,
  authenticatedUserId: string
): Promise<EventResponse> {
  const db = getDatabase();

  // Validate the Better Auth user ID format.
  if (!/^[a-fA-F0-9]{24}$/.test(authenticatedUserId)) {
    throw new Error("INVALID_AUTH_USER");
  }

  /**
   * Find the authenticated user in the
   * Better Auth user collection.
   */
  const usersCollection = db.collection<{
    name: string;
    email: string;
    image?: string | null;
  }>("user");

  const user = await usersCollection.findOne({
    _id: new ObjectId(authenticatedUserId),
  });

  if (!user) {
    throw new Error("AUTH_USER_NOT_FOUND");
  }

  /**
   * Build the event using validated input.
   *
   * The browser cannot set organizer.id,
   * organizer.name, or createdAt.
   */
  const newEvent: EventDocument = {
    title: input.title,
    description: input.description,
    eventType: input.eventType,
    thumbnailUrl: input.thumbnailUrl,
    location: input.location,
    eventDate: new Date(input.eventDate),
    createdAt: new Date(),

    organizer: {
      id: authenticatedUserId,
      name: user.name,
      ...(user.image ? { photoURL: user.image } : {}),
    },
  };

  // Insert the event into MongoDB.
  const result = await getEventsCollection().insertOne(
    newEvent
  );

  // Return frontend-friendly event data.
  return toEventResponse({
    ...newEvent,
    _id: result.insertedId,
  });
}

/**
 * GET MY EVENTS
 *
 * PURPOSE:
 * Fetch only events created by the currently
 * authenticated CommunityBond user.
 *
 * SECURITY:
 * userId comes from the verified JWT,
 * never from request body or query parameters.
 */
export async function getMyEvents(
  authenticatedUserId: string
): Promise<EventResponse[]> {
  // Reuse the existing events collection helper.
  const collection = getEventsCollection();

  // Match the organizer ID stored during event creation.
  const events = await collection
    .find({
      "organizer.id": authenticatedUserId,
    })
    .sort({
      createdAt: -1,
      _id: -1,
    })
    .toArray();

  // Convert MongoDB documents into API responses.
  return events.map(toEventResponse);
}


/**
 * DELETE EVENT
 *
 * PURPOSE:
 * Permanently delete an event created by the
 * currently authenticated organizer.
 *
 * SECURITY:
 * - Validate the MongoDB ObjectId.
 * - Check that the event exists.
 * - Verify organizer ownership.
 * - Include organizer ID in deleteOne filter.
 */

export async function deleteEvent(
  eventId: string,
  authenticatedUserId: string
): Promise<void> {
  // Validate event ID.
  if (!/^[a-fA-F0-9]{24}$/.test(eventId)) {
    throw new Error("INVALID_EVENT_ID");
  }

  const collection = getEventsCollection();
  const objectId = new ObjectId(eventId);

  // Find the existing event.
  const existingEvent = await collection.findOne({
    _id: objectId,
  });

  if (!existingEvent) {
    throw new Error("EVENT_NOT_FOUND");
  }

  // Only the original organizer can delete.
  if (
    existingEvent.organizer.id !==
    authenticatedUserId
  ) {
    throw new Error("FORBIDDEN");
  }

  // Atomic ownership-aware deletion.
  const result = await collection.deleteOne({
    _id: objectId,
    "organizer.id": authenticatedUserId,
  });

  // Detect unsuccessful deletion.
  if (result.deletedCount !== 1) {
    throw new Error("EVENT_NOT_FOUND");
  }
}
